"""Tests for the Q15 pre-submit gate.

The point of these tests is not that the verifier accepts a good recording - it is
that it *rejects* each way a recording can be wrong. A gate that passes everything
is worth nothing, so every failure mode below is a deliberately broken cast, and
each test asserts the specific complaint that should be raised.

Run:  pytest -q
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tools.verify_cast import (
    BEGIN_MARKER,
    END_MARKER,
    EXPECTED_BASE_BLOB,
    MODEL,
    PARAMS,
    SYSTEM_PROMPT,
    check_cast,
    marker_block,
    plain_lines,
)

CREATE_LINE = f"ollama create {MODEL} -f Modelfile"


def modelfile_body(*, system: str = SYSTEM_PROMPT, params: dict[str, str] | None = None) -> str:
    """The exported modelfile exactly as `ollama show --modelfile` prints it,
    including the three header comment lines (which name the built model)."""
    params = PARAMS if params is None else params
    lines = [
        '# Modelfile generated by "ollama show"',
        "# To build a new Modelfile based on this, replace FROM with:",
        f"# FROM {MODEL}:latest",
        f"FROM {EXPECTED_BASE_BLOB}",
        'TEMPLATE """{{ .Prompt }}"""',
        f"SYSTEM {system}",
    ]
    lines += [f"PARAMETER {k} {v}" for k, v in params.items()]
    return "\n".join(lines)


def write_cast(
    path: Path,
    *,
    out: str,
    inp: str,
    proof: bool = True,
    version: int = 2,
    ansi: bool = True,
) -> Path:
    """Build an asciicast v2 file. `ansi` wraps output in the escapes a TTY adds."""
    header = {"version": version, "width": 100, "height": 30, "timestamp": 0}
    if proof:
        header["proof"] = {"sub": "24f2004655@ds.study.iitm.ac.in"}
    events = []
    if ansi:
        # split mid-stream to mimic real capture: escapes and \r\n throughout
        for chunk in out.split("\n"):
            events.append([0.1, "o", "\x1b[?25l" + chunk + "\r\n\x1b[K"])
    else:
        events.append([0.1, "o", out])
    events.append([1.0, "i", inp])
    body = "\n".join(json.dumps(e) for e in events)
    path.write_text(json.dumps(header) + "\n" + body + "\n", encoding="utf-8")
    return path


GOOD_INPUT = (
    f"printf 'FROM gemma3:1b-it-qat\\nSYSTEM {SYSTEM_PROMPT}\\n"
    + "".join(f"PARAMETER {k} {v}\\n" for k, v in PARAMS.items())
    + "' > Modelfile\n"
    + CREATE_LINE
    + "\n"
    + f"printf '\\n{BEGIN_MARKER}\\n'\n"
    + f"ollama show --modelfile {MODEL}\n"
    + f"printf '\\n{END_MARKER}\\n'\n"
    + "exit\n"
)


def good_output(*, body: str | None = None, extra_before: str = "") -> str:
    body = body if body is not None else modelfile_body()
    return (
        f"$ {CREATE_LINE}\n"
        "using existing layer sha256:57c9b4a897df8d1ba26a152eb7b98e8dc743e21a5d5492f8183270565b84932b\n"
        "creating new layer sha256:25a9e08177460fd8cc35162fc5455c123563b8c6ae7b3d91bdc7aa0e13ca702b\n"
        "writing manifest\n"
        "success\n"
        + extra_before
        + f"$ printf '\\n{BEGIN_MARKER}\\n'\n{BEGIN_MARKER}\n"
        + f"$ ollama show --modelfile {MODEL}\n"
        + 'go to "https://example.invalid" for docs\n'
        + body
        + "\n"
        + f"$ printf '\\n{END_MARKER}\\n'\n{END_MARKER}\n$ exit\n"
    )


@pytest.fixture()
def good_cast(tmp_path: Path) -> Path:
    cast = write_cast(tmp_path / "model.cast", out=good_output(), inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("header.payload.signature", encoding="utf-8")
    return cast


# --------------------------------------------------------------------------- #
# the gate accepts a correct recording
# --------------------------------------------------------------------------- #


def test_a_correct_recording_passes(good_cast):
    assert check_cast(good_cast) == []


def test_plain_lines_strips_ansi_and_keeps_tab_scoped_content():
    lines = plain_lines("\x1b[1Gspinning\x1b[K\rdone\r\nok\x1b[0m\n")
    assert lines[0] == "done"          # \r overwrite keeps the last write
    assert "ok" in lines


def test_plain_lines_keeps_marker_text_when_it_is_not_the_echoed_command():
    out = f"$ printf '\\n{BEGIN_MARKER}\\n'\n{BEGIN_MARKER}\nbody\n{END_MARKER}\n"
    block = marker_block(plain_lines(out))
    assert block == ["body"], "the block must start at the printed marker, not the typed command"


# --------------------------------------------------------------------------- #
# ...and rejects each way of being wrong
# --------------------------------------------------------------------------- #


def test_wrapped_system_line_is_rejected(tmp_path):
    """A narrow terminal splits the long SYSTEM line - the classic failure."""
    broken = SYSTEM_PROMPT.replace(". ", ".\n        ", 1)
    cast = write_cast(tmp_path / "model.cast", out=good_output(body=modelfile_body(system=broken)),
                      inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    failures = check_cast(cast)
    assert any("SYSTEM line is not exact" in f for f in failures), failures


def test_duplicated_parameter_is_rejected(tmp_path):
    body = modelfile_body().replace(
        "PARAMETER seed 419", "PARAMETER seed 419\nPARAMETER seed 419"
    )
    cast = write_cast(tmp_path / "model.cast", out=good_output(body=body), inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    failures = check_cast(cast)
    assert any("exactly 1 'PARAMETER seed'" in f for f in failures), failures


def test_wrong_parameter_value_is_rejected(tmp_path):
    body = modelfile_body(params={**PARAMS, "num_predict": "075"})
    cast = write_cast(tmp_path / "model.cast", out=good_output(body=body), inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("num_predict" in f for f in check_cast(cast))


def test_a_different_base_model_is_rejected(tmp_path):
    body = modelfile_body().replace(EXPECTED_BASE_BLOB, "/blobs/sha256-deadbeef")
    cast = write_cast(tmp_path / "model.cast", out=good_output(body=body), inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("not the gemma3:1b-it-qat blob" in f for f in check_cast(cast))


def test_missing_success_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast",
                      out=good_output().replace("success\n", "error: something\n"),
                      inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("never printed 'success'" in f for f in check_cast(cast))


def test_success_after_the_marker_block_is_rejected(tmp_path):
    """A stale model from an earlier build must not satisfy the question."""
    out = good_output()
    out = out.replace("success\n", "") + "success\n"
    cast = write_cast(tmp_path / "model.cast", out=out, inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("after the marker block" in f for f in check_cast(cast))


def test_missing_end_marker_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast",
                      out=good_output().replace(END_MARKER, ""),
                      inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("marker block not found" in f or "MODELFILE_END" in f for f in check_cast(cast))


def test_missing_receipt_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(), inp=GOOD_INPUT)
    assert any("missing receipt" in f for f in check_cast(cast))


def test_unsigned_cast_without_proof_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(), inp=GOOD_INPUT, proof=False)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("no 'proof' object" in f for f in check_cast(cast))


def test_cast_without_the_create_command_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(),
                      inp=GOOD_INPUT.replace(CREATE_LINE + "\n", ""))
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("was never run inside the recording" in f for f in check_cast(cast))


def test_modelfile_never_typed_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(), inp="ollama list\nexit\n")
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    failures = check_cast(cast)
    assert any("SYSTEM prompt was never typed" in f for f in failures), failures
    assert any("FROM line was never typed" in f for f in failures), failures


def test_no_exit_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(),
                      inp=GOOD_INPUT.replace("\nexit\n", "\n"))
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("'exit' was never typed" in f for f in check_cast(cast))


def test_oversized_recording_is_rejected(tmp_path):
    cast = write_cast(tmp_path / "model.cast", out=good_output(), inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    with cast.open("ab") as handle:
        handle.write(b"x" * (5 * 1024 * 1024))
    assert any("over the 5 MB uncompressed limit" in f for f in check_cast(cast))


def test_a_corrupt_cast_is_reported_not_raised(tmp_path):
    """A truncated download must be diagnosed, not crash the gate."""
    cast = tmp_path / "model.cast"
    cast.write_text("not json at all\n", encoding="utf-8")
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    failures = check_cast(cast)
    assert any("not valid JSON" in f for f in failures), failures


def test_an_empty_cast_is_reported(tmp_path):
    cast = tmp_path / "model.cast"
    cast.write_text("", encoding="utf-8")
    failures = check_cast(cast)
    assert any("empty" in f for f in failures), failures


def test_a_recorded_secret_is_flagged(tmp_path):
    cast = write_cast(tmp_path / "model.cast",
                      out=good_output() + "export GITHUB_TOKEN=ghp_abc123\n",
                      inp=GOOD_INPUT)
    Path(str(cast) + ".jwt").write_text("x", encoding="utf-8")
    assert any("looks like a secret" in f for f in check_cast(cast))


def test_the_gate_is_not_vacuous(good_cast):
    """Every rejection above must be a rejection of something - the good cast passes."""
    assert check_cast(good_cast) == []
